const fs = require('node:fs');
const path = require('node:path');
const vm = require('node:vm');
const assert = require('node:assert/strict');
const source = fs.readFileSync(path.join(__dirname, '../web/iamccs_h3_settings_pro_ui.js'), 'utf8');
const values = {upscale_enabled:true,upscale_mode:'h3_ultimate_tiled',h3_open_refine_enabled:false,h3_open_refine_sigma_preset:'reference_3step',rife_mode:'off',h3_omni_enabled:true,steps:8,seed:42};
const node = {id:811, properties:{}, widgets:Object.entries(values).map(([name,value])=>({name,value}))};
const widget = (n,key)=>n.widgets.find(w=>w.name===key);
let connected = ['IAMCCS_MiniMaxH3OpenRefineControl'];
const context = vm.createContext({node,widget,setValue:(n,key,value)=>{const w=widget(n,key);if(w)w.value=value;},connectedNodes:()=>connected.map(type=>({type})),nodeClass:n=>n.type,shotboardMode:()=> 'ref2va',modeFamily:()=> 'ref2va',document:{dispatchEvent(){}},CustomEvent:class{}});
const constants = source.slice(source.indexOf('const NODE_TYPE ='), source.indexOf('const widget ='));
const gate = source.slice(source.indexOf('function branchGate('), source.indexOf('function modeAvailability('));
const recipes = source.slice(source.indexOf('function applyRecipe('), source.indexOf('const FACE_REFINE_PRESET_HELP'));
vm.runInContext(constants + gate + recipes + 'globalThis.apply=applyRecipe;globalThis.layout=FUNCTIONAL_LAYOUT;globalThis.groups=GROUPS;',context);
assert.equal(context.apply(node,'open-h3-refine'),true);
assert.equal(widget(node,'h3_open_refine_enabled').value,true);
assert.equal(widget(node,'upscale_enabled').value,false);
assert.equal(widget(node,'upscale_mode').value,'off');
assert.equal(widget(node,'h3_open_refine_sigma_preset').value,'gentle_3step');
assert.equal(widget(node,'h3_omni_enabled').value,true);
assert.equal(widget(node,'steps').value,8);
assert.equal(widget(node,'seed').value,42);
context.apply(node,'native-delivery');
assert.equal(widget(node,'h3_open_refine_enabled').value,false);
connected=[];
assert.equal(context.apply(node,'open-h3-refine'),false);
assert.equal(widget(node,'h3_open_refine_enabled').value,false);
const section=context.layout.finish.find(([title])=>title.startsWith('OPEN-H3 REFINEMENT'));
assert.equal(section[1].length,14);
assert.ok(context.groups.find(g=>g.id==='finish').fields.includes('h3_open_refine_seed'));
assert.match(source,/addRecipe\(delivery, "OPEN-H3 REFINEMENT/);
console.log('PASS: Mode Assistant selection, separate Output box, lazy-branch gate and one-native-generation settings');
